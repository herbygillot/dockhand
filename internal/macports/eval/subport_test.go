// The corpus fixtures are asked for by name and staged by testenv; a
// portdir is the only form a Portfile is evaluable in, so the accessor
// hands one back.
func fixturePortdir(t *testing.T, name string) string {
	t.Helper()
	return testenv.PortfileDir(t, name)
}

func key(subport string) info.SubportKey {
	return info.SubportKey{Subport: subport}
}

// libftdi declares its subports statically: the top-level port is an
// obsolete stub while libftdi0 and libftdi1 stay live, with per-context
// values that differ from the top level's.
func TestSnapshotStaticSubports(t *testing.T) {
	e := newEvaluator(t)
	dir := fixturePortdir(t, "devel__libftdi")
	snap, err := e.Snapshot(context.Background(), dir, "")
	require.NoError(t, err)
	require.Len(t, snap, 3)

	top := snap[key("libftdi")]
	require.Equal(t, "0.20", top.Version)
	require.Equal(t, "1", top.Epoch)

	require.Equal(t, "0.20", snap[key("libftdi0")].Version)
	require.Equal(t, "1", snap[key("libftdi0")].Revision)
	require.Equal(t, "1.5", snap[key("libftdi1")].Version)
	require.Equal(t, "2", snap[key("libftdi1")].Revision)

	// Per-context depends, observed. Note the top-level stub still carries
	// depends_lib: the obsolete PortGroup clears it when the group loads,
	// but the Portfile's later depends_lib-append runs after that and
	// re-adds it — evaluation-order truth the oracle reports, and the kind
	// of fact no textual reasoning gets right (this assertion originally
	// guessed Empty and was corrected by the evaluator).
	require.Equal(t, []string{"port:libusb-compat"}, top.Depends.Lib)
	require.Equal(t, []string{"port:libusb-compat"}, snap[key("libftdi0")].Depends.Lib)
	require.Contains(t, snap[key("libftdi0")].Depends.Build, "port:pkgconfig")
	require.Equal(t, []string{"GPL-2+"}, snap[key("libftdi0")].License)
}

// py-hid's subports are generated by the python PortGroup at evaluation
// time — no subport command appears in the Portfile's text. This is the
// case that proves enumeration must come from evaluation.
func TestSnapshotGeneratedSubports(t *testing.T) {
	e := newEvaluator(t)
	dir := fixturePortdir(t, "python__py-hid")
	snap, err := e.Snapshot(context.Background(), dir, "")
	require.NoError(t, err)

	require.Contains(t, snap, key("py-hid"))
	require.Contains(t, snap, key("py310-hid"))
	require.Contains(t, snap, key("py311-hid"))
	for k, v := range snap {
		require.NotEmpty(t, v.Version, "context %v", k)
	}
}

// A port with no subports field yields exactly its one context.
func TestSnapshotNoSubports(t *testing.T) {
	e := newEvaluator(t)
	dir := fixturePortdir(t, "math__ivy")
	snap, err := e.Snapshot(context.Background(), dir, "")
	require.NoError(t, err)
	require.Len(t, snap, 1)
	require.Contains(t, snap, key("ivy"))
}

// A handwritten subport block, hermetic in content: per-context values
// come from each context's own evaluation, not the top level's.
func TestSnapshotInlineSubport(t *testing.T) {
	e := newEvaluator(t)
	dir := portdirWith(t, `PortSystem 1.0
name                multi
version             1.0
categories          devel
subport multi-sub {
    version         2.0
}
`)
	snap, err := e.Snapshot(context.Background(), dir, "")
	require.NoError(t, err)
	require.Len(t, snap, 2)
	require.Equal(t, "1.0", snap[key("multi")].Version)
	require.Equal(t, "2.0", snap[key("multi-sub")].Version)
}

func TestSubports(t *testing.T) {
	e := newEvaluator(t)
	dir := fixturePortdir(t, "devel__libftdi")
	subs, err := e.Subports(context.Background(), dir)
	require.NoError(t, err)
	require.Equal(t, []string{"libftdi0", "libftdi1"}, subs)
}

// Variants are a real evaluation frame: a variant that appends a
// dependency changes the context's values, and the snapshot's keys carry
// the frame they were taken under.
func TestSnapshotWithVariants(t *testing.T) {
	e := newEvaluator(t)
	dir := portdirWith(t, `PortSystem 1.0
name varport
version 1.0
categories devel
variant extra description {more deps} {
    depends_lib-append port:zlib
}
`)
	vs, err := info.Variants("+extra")
	require.NoError(t, err)

	plain, err := e.Snapshot(context.Background(), dir, "")
	require.NoError(t, err)
	require.Empty(t, plain[info.SubportKey{Subport: "varport"}].Depends.Lib)

	withVar, err := e.Snapshot(context.Background(), dir, vs)
	require.NoError(t, err)
	v, ok := withVar[info.SubportKey{Subport: "varport", Variants: vs}]
	require.True(t, ok, "keys must carry the variant frame")
	require.Equal(t, []string{"port:zlib"}, v.Depends.Lib)

	// Different frames diff as membership churn, per the Delta contract.
	d := plain.Diff(withVar)
	require.Len(t, d.Added, 1)
	require.Len(t, d.Removed, 1)
}
